def copy_cover(b: dict) -> tuple[int, int]:
    """cover.jpg, at most 900px on its long side. Remade only when the source is newer."""
    dest = os.path.join(OUT, b["url"], "cover.jpg")
    if not os.path.exists(dest) or os.path.getmtime(dest) < os.path.getmtime(b["cover"]):
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            t = os.path.join(tmp, "cover.jpg")
            shutil.copyfile(b["cover"], t)
            if shutil.which("sips"):
                subprocess.run(["sips", "-Z", "900", t], capture_output=True, check=False)
            shutil.copyfile(t, dest)
        written.append(os.path.relpath(dest, SITE))
    return jpeg_size(dest)


