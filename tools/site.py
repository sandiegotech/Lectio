def fill(text: str, tokens: dict) -> str:
    def sub(m):
        key = m.group(1)
        if key not in tokens:
            sys.exit(f"site.py: unknown token {{{{{key}}}}} in catalog/pages")
        return str(tokens[key])
    return re.sub(r"\{\{(\w+)\}\}", sub, text)


def prose_page(spec: dict, tokens: dict, inserts: dict) -> str:
    """The sections of _index.json or _mission.json as article blocks."""
    out = []
    for i, s in enumerate(spec["sections"]):
        parts = [f"          <h2>{fill(s['h2'], tokens)}</h2>"]
        for blk in s["body"]:
            if isinstance(blk, dict):
                if "insert" in blk:
                    parts.append("          " + inserts[blk["insert"]])
                elif "status" in blk:
                    parts.append(f"""          <div class="status{' lx-status' if blk.get('beta') else ''}">
            <span class="s-label">{fill(esc(blk['status']), tokens)}</span>
            {fill(blk['text'], tokens)}
          </div>""")
                elif "list" in blk:
                    lis = "\n".join(f"            <li>{fill(x, tokens)}</li>" for x in blk["list"])
                    parts.append(f"          <{blk.get('tag', 'ul')} class=\"lx-list\">\n{lis}\n          </{blk.get('tag', 'ul')}>")
                elif "sub" in blk:
                    parts.append(f"          <h3 class=\"lx-sub\">{fill(blk['sub'], tokens)}</h3>")
                elif "cta" in blk:
                    parts.append(f"          <a class=\"cta\" href=\"{blk['href']}\">{fill(blk['cta'], tokens)} →</a>")
            else:
                cls = ' class="lede"' if blk.startswith("!") else ""
                parts.append(f"          <p{cls}>{fill(blk.lstrip('!'), tokens)}</p>")
        out.append(article(fill(s["label"], tokens), fill(s["num"], tokens), "\n".join(parts), s["id"],
                           tail=(i == len(spec["sections"]) - 1)))
    return "".join(out)


