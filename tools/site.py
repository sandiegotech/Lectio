def crumbs(trail: list[tuple[str, str | None]]) -> str:
    items = []
    for name, href in trail:
        items.append(f'<li><a href="{href}">{esc(name)}</a></li>' if href
                     else f'<li aria-current="page">{esc(name)}</li>')
    return ('<nav class="lx-crumbs" aria-label="Breadcrumb"><ol>' + "".join(items) + "</ol></nav>")


