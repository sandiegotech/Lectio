def check(library: list[dict]) -> None:
    from html.parser import HTMLParser

    class P(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=True)
            self.h1 = 0
            self.hrefs, self.srcs = [], []
            self.title = self.desc = self.canon = None
            self._in = None
            self.passage, self._pdepth, self._cur = [], 0, None
            self.text = []
            self._skip = 0

        def handle_starttag(self, tag, attrs):
            a = dict(attrs)
            if tag == "h1":
                self.h1 += 1
            if tag == "title":
                self._in = "title"
            if tag in ("script", "style", "dd", "blockquote"):
                self._skip += 1          # dd and blockquote hold quoted text, not our prose
            if tag == "meta" and a.get("name") == "description":
                self.desc = a.get("content")
            if tag == "link" and a.get("rel") == "canonical":
                self.canon = a.get("href")
            if tag == "a" and a.get("href"):
                self.hrefs.append(a["href"])
            if tag in ("img", "script") and a.get("src"):
                self.srcs.append(a["src"])
            if tag == "link" and a.get("rel") in ("stylesheet", "icon", "apple-touch-icon", "manifest", "alternate") and a.get("href"):
                self.srcs.append(a["href"])
            if tag == "div" and "lx-passage" in (a.get("class") or ""):
                self._pdepth = 1
            elif tag == "div" and self._pdepth:
                self._pdepth += 1
            if self._pdepth and tag == "p":
                self._cur = dict(cls=a.get("class") or "", text="")
            if self._pdepth and tag == "br" and self._cur is not None:
                self._cur["text"] += "\n"

        def handle_endtag(self, tag):
            if tag == "title":
                self._in = None
            if tag in ("script", "style", "dd", "blockquote"):
                self._skip -= 1
            if tag == "div" and self._pdepth:
                self._pdepth -= 1
            if tag == "p" and self._cur is not None:
                self.passage.append(self._cur)
                self._cur = None

        def handle_data(self, data):
            if self._in == "title":
                self.title = (self.title or "") + data
            if self._cur is not None:
                self._cur["text"] += data
            if not self._skip and not self._pdepth:
                self.text.append(data)

    def bad(page, msg):
        problems.append(f"{page}: {msg}")

    by_url = {b["url"]: b for b in library}
    pages = sorted(glob.glob(os.path.join(OUT, "**", "*.html"), recursive=True))
    titles, descs = {}, {}
    for f in pages:
        rel = os.path.relpath(f, SITE)
        raw = open(f, encoding="utf-8").read()
        p = P()
        p.feed(raw)
        if p.h1 != 1:
            bad(rel, f"{p.h1} <h1> elements")
        if not (p.title or "").strip():
            bad(rel, "no <title>")
        if not (p.desc or "").strip():
            bad(rel, "no meta description")
        elif not 110 <= len(p.desc) <= 160:
            bad(rel, f"description is {len(p.desc)} characters, want 110 to 160")
        if len((p.title or "")) > 65:
            bad(rel, f"title is {len(p.title)} characters, want 65 or fewer")
        if raw.count('rel="canonical"') != 1:
            bad(rel, f"{raw.count('rel=canonical')} canonical links")
        for tag in re.findall(r"<img\b[^>]*>", raw):
            if not all(k in tag for k in (' width="', ' height="', ' alt="')):
                bad(rel, f"img without width, height or alt: {tag[:60]}")
        m = re.search(r'<meta property="og:image" content="([^"]+)"', raw)
        og = os.path.join(SITE, m.group(1)[len(BASE):].lstrip("/")) if m and m.group(1).startswith(BASE) else ""
        if not og or not os.path.isfile(og):
            bad(rel, "og:image file is missing")
        elif jpeg_size(og) != (1200, 630):
            bad(rel, f"og:image is {jpeg_size(og)}, want 1200x630")
        for twin in ("index.md",) + (("edition.json",) if os.path.basename(os.path.dirname(f)) in by_url else ()):
            t = os.path.join(os.path.dirname(f), twin)
            if not os.path.isfile(t) or not os.path.getsize(t):
                bad(rel, f"no {twin} beside the page")
        want = BASE + "/" + os.path.dirname(rel) + "/"
        if p.canon != want:
            bad(rel, f"canonical {p.canon!r}, expected {want!r}")
        titles.setdefault(p.title, []).append(rel)
        descs.setdefault(p.desc, []).append(rel)
        if "application/ld+json" not in raw:
            bad(rel, "no JSON-LD")
        else:
            try:
                graph = json.loads(raw.split('<script type="application/ld+json">', 1)[1].split("</script>", 1)[0].replace("<\\/", "</"))
                ids = {n.get("@id") for n in graph.get("@graph", [])}

                def refs(node):
                    if isinstance(node, dict):
                        if set(node) == {"@id"}:
                            yield node["@id"]
                        for v in node.values():
                            yield from refs(v)
                    elif isinstance(node, list):
                        for v in node:
                            yield from refs(v)
                for r in sorted(set(refs(graph)) - ids):
                    bad(rel, f"JSON-LD refers to {r}, which is not in the graph")
            except ValueError as e:
                bad(rel, f"JSON-LD does not parse: {e}")
        # links and assets resolve to files
        for ref in p.hrefs + p.srcs:
            if ref.startswith(("http://", "https://", "mailto:", "#")):
                if ref.startswith(BASE):
                    ref = ref[len(BASE):] or "/"
                else:
                    continue
            target = ref.split("#")[0].split("?")[0]
            full = os.path.join(SITE, target.lstrip("/")) if target.startswith("/") else os.path.join(os.path.dirname(f), target)
            if target.endswith("/") or os.path.isdir(full):
                full = os.path.join(full, "index.html")
            if not os.path.isfile(full):
                bad(rel, f"link does not resolve: {ref}")
        # the status line says "beta"; the overview carries the Scholars section
        status = re.findall(r'class="[^"]*lx-status[^"]*"[^>]*>(.*?)</(?:div|dd)>', raw, re.S)
        if not any("beta" in x.lower() for x in status):
            bad(rel, 'no status line with the word "beta"')
        if rel == os.path.join("lectio", "index.html"):
            m = re.search(r'<section[^>]*id="scholars".*?</section>', raw, re.S)
            if not m or "mailto:" not in m.group(0) or "Join the review" not in m.group(0):
                bad(rel, "no Scholars section with its Join the review link")
        # words that must not appear
        low = raw.lower()
        for word in ("todo", "lorem", "human-reviewed", "download now"):
            if word in low:
                bad(rel, f"contains {word!r}")
        if re.search(r'<a\b[^>]*>[^<]*App Store|App Store[^<]{0,80}<a\b|href="[^"]*apps\.apple\.com', raw):
            bad(rel, "'App Store' beside a link")
        if "!" in "".join(p.text).replace("!important", ""):
            bad(rel, "exclamation mark outside a quoted passage")
        for line in "".join(p.text).splitlines():
            if line.count("—") >= 3:
                bad(rel, f"dash-heavy line: {line.strip()[:70]}")
        # the opening passage is the bundle text, exactly
        slug = os.path.basename(os.path.dirname(f))
        if slug in by_url:
            ed = by_url[slug]["lectio"]
            segs = [g["text"] for s in ed["sections"] for g in s["segments"] if g.get("kind") != "omit"]
            shown = [x["text"] for x in p.passage if "lx-sec" not in x["cls"]]
            if not shown:
                bad(rel, "no opening passage")
            n = 0
            for i, t in enumerate(shown):
                n += words(t)
                if i >= len(segs) or not (segs[i] == t or (i == len(shown) - 1 and segs[i].startswith(t))):
                    bad(rel, f"opening paragraph {i + 1} is not the bundle text")
            if not 150 <= n <= 250:
                bad(rel, f"opening passage is {n} words")
            # every quoted Lectio rendering in the divergence list is in the edition
            text = _norm(" ".join(segs))
            for d in by_url[slug]["page"]["divergences"]:
                if d.get("verbatim", True):
                    for piece in re.split(r"\s*(?:\.\.\.|…)\s*", d["lectio"]):
                        piece = _norm(piece.replace(" / ", " ").replace("*", "")).strip(" .")
                        if piece and piece not in text:
                            bad(rel, f"divergence wording not found in the edition: {piece[:60]!r}")
        book = by_url.get(os.path.basename(os.path.dirname(os.path.dirname(f))))
        if book and slug not in by_url:
            ch = next((c for c in chapters_of(book) if c["slug"] == slug), None)
            shown = [x["text"] for x in p.passage]
            if not ch:
                bad(rel, "a page of text for no section in the bundle")
            elif shown != [seg_text(g["text"]) for g in ch["segs"]]:
                bad(rel, "the text is not the bundle text")
    for b in library:
        for c in chapters_of(b):
            if not os.path.isfile(os.path.join(SITE, c["path"].strip("/"), "index.html")):
                problems.append(f"{c['path']}: no page for this section")
    for what, seen in (("title", titles), ("description", descs)):
        for k, v in seen.items():
            if len(v) > 1:
                problems.append(f"duplicate {what} on {', '.join(v)}")

    # the machine-readable files: present, non-empty, and pointing at real pages
    def resolves(url: str) -> bool:
        target = url[len(BASE):].split("#")[0].lstrip("/")
        full = os.path.join(SITE, target)
        if target == "" or target.endswith("/") or os.path.isdir(full):
            full = os.path.join(full, "index.html")
        return os.path.isfile(full)

    for rel in ("llms.txt", "llms-full.txt", os.path.join("lectio", "feed.xml"), os.path.join("lectio", "editions.json")):
        full = os.path.join(SITE, rel)
        if not os.path.isfile(full) or not os.path.getsize(full):
            problems.append(f"{rel}: missing or empty")
            continue
        text = open(full, encoding="utf-8").read()
        if rel.endswith(("llms.txt", "feed.xml")):
            for url in sorted(set(re.findall(re.escape(BASE) + r"[^\s\")<>]*", text))):
                if not resolves(url):
                    problems.append(f"{rel}: {url} does not resolve to a file")
        if rel.endswith(".xml"):
            import xml.etree.ElementTree as ET
            try:
                root = ET.fromstring(text)
                n = len(root.findall("{http://www.w3.org/2005/Atom}entry"))
                if n != len(library):
                    problems.append(f"{rel}: {n} entries for {len(library)} editions")
            except ET.ParseError as e:
                problems.append(f"{rel}: not well-formed XML: {e}")
        if rel.endswith(".json"):
            try:
                if json.loads(text)["count"] != len(library):
                    problems.append(f"{rel}: count does not match the library")
            except (ValueError, KeyError) as e:
                problems.append(f"{rel}: {e}")
    for b in library:
        try:
            load(os.path.join(OUT, b["url"], "edition.json"))
        except (OSError, ValueError) as e:
            problems.append(f"lectio/{b['url']}/edition.json: {e}")

    # robots.txt keeps the training reservation and every crawler it named
    robots = open(os.path.join(SITE, "robots.txt"), encoding="utf-8").read() if os.path.exists(os.path.join(SITE, "robots.txt")) else ""
    if "ai-train=no" not in robots:
        problems.append("robots.txt: ai-train=no is gone")
    for bot in ("Amazonbot", "Applebot-Extended", "Bytespider", "CCBot", "ClaudeBot", "Google-Extended", "GPTBot", "meta-externalagent"):
        if not re.search(r"User-agent: " + re.escape(bot) + r"\s*\nDisallow: /\s*(\n|$)", robots):
            problems.append(f"robots.txt: {bot} is no longer disallowed")


def _norm(s: str) -> str:
    s = s.replace("“", '"').replace("”", '"').replace("‘", "'").replace("’", "'")
    return re.sub(r"\s+", " ", s)


