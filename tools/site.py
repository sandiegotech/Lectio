#!/usr/bin/env python3
"""Write the Lectio section of sandiegotech.org from the register and the bundle.

    python3 tools/site.py              # rebuild every page, then the site's sitemap
    python3 tools/site.py --check      # rebuild, then verify what was written
    python3 tools/site.py --no-sitemap # leave ../website/sitemap.xml alone
    python3 tools/site.py --cards      # remake every share card, not only the stale ones

Output goes to ../website/lectio/, plus two files at the site root, llms.txt and
llms-full.txt (the sitemap is regenerated by the site's own infra/build_sitemap.py).
Nothing is deployed.

For each page it writes, beside index.html:

    index.md        the same page as plain Markdown, for machine readers
    share.jpg       a 1200x630 card for link previews
    edition.json    the edition's public record as data (edition pages only)

and once: lectio/editions.json, lectio/feed.xml (Atom), /llms.txt, /llms-full.txt.
Titles and descriptions for search come from "seo" in each catalog/pages file, with a
generated fallback, so a new book gets all of this by having a page file.

Dependencies beyond the standard library, both optional: `typst` sets the share cards
(the same tool print/ uses) and macOS `sips` converts them to JPEG and resizes covers.
Without them the build still succeeds: a page's preview image falls back to its cover.

What is derived, so the site, the app and the book cannot disagree:

    catalog/books.json          order, titles, release dates, approval
    content/works/<id>/         work.json, every edition, cover.jpg, the opening passage,
                                provenance (model, drafting date, vintage, revised, sources)
    review/<run>/RUN.md         sections read, grades, fixes by severity
    review/<run>/<slug>/        patch*.json, cross-checked against RUN.md
    PLAN.md section 4           the model comparison table

What a person writes, in catalog/pages/:

    <slug>.json                 one per book: what it is, why this edition, the choices,
                                a handful of divergences, what is still open
    _index.json  _mission.json  the prose of /lectio/ and /lectio/mission/

Text in <slug>.json is plain; *asterisks* mark italics. Text in _index.json and
_mission.json is HTML, with {{tokens}} filled from the data above.

Running it twice writes nothing the second time.
"""
