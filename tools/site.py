def real_author(b: dict) -> str:
    """The author as a person's name, or '' for anonymous and collective works."""
    a = b["work"].get("author") or ""
    return "" if ("Anonymous" in a or "tradition" in a) else a


def is_translation(b: dict) -> bool:
    return b["work"].get("originalLang") != "en"


def seo_of(b: dict) -> tuple[str, str]:
    """Title and description for search: hand-written under "seo", else generated."""
    seo = b["page"].get("seo", {})
    t, a = b["work"]["title"], real_author(b)
    kind = "translation" if is_translation(b) else "edition"
    title = seo.get("title") or f"{t}{' by ' + a if a else ''}: a modern English {kind} · Lectio"
    if len(title) > 65:
        title = f"{t}: a modern English {kind} · Lectio"
    return title, seo.get("description") or b["page"]["description"]


def citation(b: dict) -> str:
    prov, a = b["lectio"]["provenance"], real_author(b)
    return (f"{a + '. ' if a else ''}{b['work']['title']}. Lectio Edition. {ORG}, {prov.get('vintage')} vintage, "
            f"revised {long_date(prov['revised'])}. {BASE}/lectio/{b['url']}/")


def related_of(b: dict, library: list[dict]) -> list[dict]:
    """Two or three editions to read next: the hand-written list, else same genre, then same tradition."""
    by_slug = {x["slug"]: x for x in library}
    picks = [by_slug[s] for s in b["page"].get("related", []) if s in by_slug and s != b["slug"]]
    if not picks:
        same = [x for x in library if x is not b and x["work"].get("type") == b["work"].get("type")]
        trad = [x for x in library if x is not b and x not in same and x["work"].get("tradition") == b["work"].get("tradition")]
        picks = same + trad
    return picks[:3]


def edition_record(b: dict) -> dict:
    """The edition's public record as data: what edition.json holds."""
    w, ed, prov, r = b["work"], b["lectio"], b["lectio"]["provenance"], b["review"]
