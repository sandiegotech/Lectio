def to_markdown(page_html: str, path: str) -> str:
    """The <main> of one generated page as plain Markdown: same words, no chrome."""
    from html.parser import HTMLParser
    main = page_html.split('<main id="top">', 1)[1].split("</main>", 1)[0]
    BLOCKS = {"h1", "h2", "h3", "p", "li", "dt", "dd", "blockquote", "figcaption", "tr"}

    class M(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=True)
            self.out, self.buf, self.kind = [], None, None
            self.skip = 0
            self.lists, self.dt = [], ""
            self.quote = 0
            self.href = []
            self.cells, self.row_n = None, 0

        def open(self, kind):
            self.close()
            self.buf, self.kind = [], kind

        def close(self):
            if self.buf is None:
                return
            text = re.sub(r"[ \t\r\f\v]+", " ", "".join(self.buf)).strip()
            text = re.sub(r" ?\n ?", "  \n", text)
            kind, self.buf, self.kind = self.kind, None, None
            if kind == "td":
                self.cells.append(text.replace("|", "/"))
                return
            if not text:
                return
            pre = "> " if self.quote else ""
            if kind in ("h1", "h2", "h3"):
                text = "#" * int(kind[1]) + " " + text
            elif kind == "li":
                mark = "- " if not self.lists or self.lists[-1] is None else f"{self.lists[-1]}. "
                self.out.append(pre + mark + text)
                return
            elif kind == "dt":
                self.dt = text
                return
            elif kind == "dd":
                text = f"**{self.dt}:** {text}"
                self.dt = ""
            elif kind in ("label", "figcaption"):
                text = f"**{text}**"
            elif kind == "blockquote":
                pre = "> "
            self.out.append("")
            self.out.append("\n".join(pre + l for l in text.split("\n")))

        def handle_starttag(self, tag, attrs):
            a = dict(attrs)
            cls = a.get("class") or ""
            if self.skip or tag in ("script", "style") or "lx-crumbs" in cls or "article-label" in cls:
                self.skip += 1 if tag not in ("img", "br", "meta", "link") else 0
                return
            if tag in ("ul", "ol"):
                if self.kind == "dd" and self.buf is not None and not "".join(self.buf).strip():
                    self.buf, self.kind = None, None
                    self.out += ["", f"**{self.dt}:**"]
                    self.dt = ""
                else:
                    self.close()
                self.out.append("")
                self.lists.append(1 if tag == "ol" else None)
            elif tag == "tr":
                self.close()
                self.cells = []
            elif tag in ("td", "th"):
                self.buf, self.kind = [], "td"
            elif tag in BLOCKS:
                self.open("label" if "lx-sec" in cls else tag)
            elif tag == "div":
                self.close()
                if "lx-passage" in cls and "lx-read" not in cls:   # a whole section is the page, not a quotation
                    self.quote += 1
                if "status" in cls.split():
                    self.buf, self.kind = [], "p"
            elif tag == "section":
                self.close()
            elif tag == "br" and self.buf is not None:
                self.buf.append("\n")
            elif tag in ("em", "i") and self.buf is not None:
                self.buf.append("*")
            elif tag in ("strong", "b") and self.buf is not None:
                self.buf.append("**")
            elif tag == "code" and self.buf is not None:
                self.buf.append("`")
            elif tag == "a":
                if self.buf is None:
                    self.buf, self.kind = [], "p"
                href = a.get("href", "")
                if href.startswith("/"):
                    href = BASE + href
                elif href.startswith("#"):
                    href = BASE + path + href
                elif not re.match(r"[a-z]+:", href):
                    href = BASE + path + href
                self.href.append(href)
                self.buf.append("[")
            elif tag == "span" and "s-label" in cls and self.buf is not None:
                self.buf.append("**")
                self.href.append(None)

        def handle_endtag(self, tag):
            if self.skip:
                self.skip -= 1
                return
            if tag in ("ul", "ol"):
                self.close()
                if self.lists:
                    self.lists.pop()
                self.out.append("")
            elif tag in ("td", "th"):
                self.close()
            elif tag == "tr":
                if self.cells is not None:
                    if self.row_n == 0:
                        self.out.append("")
                    self.out.append("| " + " | ".join(self.cells) + " |")
                    if self.row_n == 0:
                        self.out.append("|" + " --- |" * len(self.cells))
                    self.row_n += 1
                self.cells = None
            elif tag == "table":
                self.row_n = 0
                self.out.append("")
            elif tag == "li":
                self.close()
                if self.lists and self.lists[-1] is not None:
                    self.lists[-1] += 1
            elif tag in BLOCKS:
                self.close()
            elif tag == "div":
                self.close()
                if self.quote:
                    self.quote -= 1
            elif tag in ("em", "i") and self.buf is not None:
                self.buf.append("*")
            elif tag in ("strong", "b") and self.buf is not None:
                self.buf.append("**")
            elif tag == "code" and self.buf is not None:
                self.buf.append("`")
            elif tag == "a" and self.buf is not None and self.href:
                self.buf.append(f"]({self.href.pop()})")
            elif tag == "span" and self.href and self.href[-1] is None and self.buf is not None:
                self.href.pop()
                self.buf.append(":** ")

        def handle_data(self, data):
            if self.skip:
                return
            if self.buf is None:
                if not data.strip():
                    return
                self.buf, self.kind = [], "p"
            self.buf.append(re.sub(r"\s+", " ", data))

    m = M()
    m.feed(main)
    m.close()
    text = "\n".join(m.out)
    # the passage div counts nested divs loosely; a quote never runs past a heading
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text.replace(" →", "").replace("← ", "") + "\n"


def front_block(fields: list[tuple[str, str]]) -> str:
    return "---\n" + "\n".join(f"{k}: {v}" for k, v in fields if v) + "\n---\n\n"


