def drafted(slug: str) -> bool:
    return any(os.path.isdir(os.path.join(ROOT, "drafts", s)) for s in (slug, slug.replace("the-", "", 1)))


def schedule_html(register: list[dict], library: list[dict]) -> tuple[str, dict]:
    in_lib = {b["slug"]: b for b in library}
    launch = [b for b in register if b.get("release") == "launch"]
    dated = sorted((b for b in register if re.fullmatch(r"\d{4}-\d\d-\d\d", str(b.get("release")))),
                   key=lambda b: b["release"])
    pending = [b for b in launch if b["slug"] not in in_lib]
    rows = "\n".join(f"              <tr><td>{esc(long_date(b['release']))}</td><td><em>{esc(b['title'])}</em></td><td>{esc(b['author'])}</td></tr>"
                     for b in dated)
    table = f"""<div class="lx-table-wrap">
            <table class="lx-table">
              <thead><tr><th>Monday</th><th>Book</th><th>Author</th></tr></thead>
              <tbody>
{rows}
              </tbody>
            </table>
          </div>"""
    names = [f"<em>{esc(b['title'])}</em>" + (f" ({esc(b['author'])})" if b.get("author") else "") for b in pending]
    facts = dict(n_launch=len(launch), n_pending=len(pending), n_dated=len(dated),
                 pending_names=", ".join(names[:-1]) + (" and " if len(names) > 1 else "") + names[-1] if names else "",
                 pending_all_drafted=all(drafted(b["slug"]) for b in pending),
                 first_monday=long_date(dated[0]["release"]) if dated else "",
                 last_monday=long_date(dated[-1]["release"]) if dated else "")
    return table, facts


