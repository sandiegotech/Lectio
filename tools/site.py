def pdf_for(b: dict) -> dict | None:
    """The revised PDF if it has been set and copied in; else nothing."""
    spec = b["page"].get("pdf")
    if not spec:
        return None
    dest = os.path.join(OUT, b["url"], spec["name"])
    src = os.path.join(ROOT, spec["source"])
    revised = b["lectio"]["provenance"].get("revised", "")
    stamp = __import__("datetime").date.fromtimestamp(os.path.getmtime(src)).isoformat() if os.path.exists(src) else ""
    if stamp and stamp >= revised:      # a PDF set before the last revision is not this text
        with open(src, "rb") as f:
            write(dest, f.read())
    if os.path.exists(dest):
        mb = os.path.getsize(dest) / 1e6
        return dict(href=f"/lectio/{b['url']}/{spec['name']}", label=spec["label"], mb=mb)
    return None


