# ---------------------------------------------------------------- small helpers

def esc(s) -> str:
    return html.escape(str(s), quote=True)


def rich(s: str) -> str:
    """Plain hand-written text to HTML: escaped, with *italics*."""
    return re.sub(r"\*([^*\n]+)\*", r"<em>\1</em>", esc(s))


def load(path: str):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def long_date(iso: str) -> str:
    y, m, d = (int(x) for x in iso.split("-"))
    return f"{MONTHS[m - 1]} {d}, {y}"


def month_year(iso: str) -> str:
    y, m, _ = (int(x) for x in iso.split("-"))
    return f"{MONTHS[m - 1]} {y}"


def model_name(mid: str) -> str:
    return MODEL_NAMES.get(mid, mid or "unrecorded")


def url_slug(slug: str) -> str:
    return slug[6:] if slug.startswith("bible-") else slug


def words(s: str) -> int:
    return len(s.split())


NUMBER_WORDS = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def count_word(n: int, one: str, many: str | None = None) -> str:
    """Like plural(), with small numbers spelled out: 'one other edition'."""
    num = NUMBER_WORDS[n] if 0 <= n < len(NUMBER_WORDS) else f"{n:,}"
    return f"{num} {one if n == 1 else (many or one + 's')}"


def plural(n: int, one: str, many: str | None = None) -> str:
    return f"{n:,} {one if n == 1 else (many or one + 's')}"


def write(path: str, data: str | bytes) -> None:
    """Write only when the content differs, so a second run changes nothing."""
    raw = data.encode("utf-8") if isinstance(data, str) else data
    if os.path.exists(path):
        with open(path, "rb") as f:
            if f.read() == raw:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(raw)
    written.append(os.path.relpath(path, SITE))


def jpeg_size(path: str) -> tuple[int, int]:
    with open(path, "rb") as f:
        data = f.read()
    i = 2
    while i < len(data) - 9:
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", data[i + 5:i + 9])
            return w, h
        i += 2 + struct.unpack(">H", data[i + 2:i + 4])[0]
    return 0, 0


def unit_of(label: str) -> tuple[str, str]:
    low = (label or "").lower()
    for key, one, many in (("canto", "canto", "cantos"), ("book", "book", "books"),
                           ("act", "act", "acts"), ("tablet", "tablet", "tablets"),
                           ("chapter", "chapter", "chapters")):
        if key in low:
            return one, many
    return "section", "sections"


# ---------------------------------------------------------------- the data

def parse_run() -> dict:
    """The per-work table in review/<run>/RUN.md."""
    rows = {}
    for line in open(os.path.join(REVIEW, "RUN.md"), encoding="utf-8"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 7 and re.fullmatch(r"[a-z-]+", cells[0]) and cells[1].isdigit():
            rows[cells[0]] = dict(sections=int(cells[1]), a=int(cells[2]), b=int(cells[3]),
                                  high=int(cells[4]), medium=int(cells[5]), low=int(cells[6]))
    return rows


def patch_counts(slug: str) -> dict:
    c = {"high": 0, "medium": 0, "low": 0}
    for f in glob.glob(os.path.join(REVIEW, slug, "patch*.json")):
        for e in load(f):
            if e.get("seg") is not None:
                c[e["severity"]] += 1
    return c


def parse_model_table() -> list[dict]:
    """PLAN.md part 4: faults by drafting model."""
    text = open(os.path.join(ROOT, "PLAN.md"), encoding="utf-8").read()
    part = text.split("## 4. Models and vintages", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in part.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 4 and cells[1].isdigit():
            rows.append(dict(model=cells[0], works=int(cells[1]), faults=cells[2], meaning=cells[3]))
    if not rows:
        sys.exit("site.py: could not read the model table in PLAN.md part 4")
    return rows


def load_books() -> tuple[list[dict], list[dict]]:
    """The register, and the subset that is in the bundle with a Lectio edition."""
    register = load(os.path.join(ROOT, "catalog", "books.json"))
    run = parse_run()
    library = []
    for b in register:
        if not b.get("workId"):
            continue
        wd = os.path.join(WORKS, b["workId"])
        work = load(os.path.join(wd, "work.json"))
        editions = {}
        for f in glob.glob(os.path.join(wd, "editions", "*.json")):
            e = load(f)
            editions[e["id"]] = e
        lectio = next((e for e in editions.values() if e.get("kind") == "modern"), None)
        if not lectio:
            continue
        slug = b["slug"]
        page_file = os.path.join(PAGES, slug + ".json")
        if not os.path.exists(page_file):
            sys.exit(f"site.py: no hand-written copy for {slug} (catalog/pages/{slug}.json)")
        review = run.get(slug)
        if review:
            got = patch_counts(slug)
            want = {k: review[k] for k in ("high", "medium", "low")}
            if got != want:
                sys.exit(f"site.py: {slug}: patch files {got} disagree with RUN.md {want}")
        library.append(dict(
            reg=b, slug=slug, url=url_slug(slug), work=work, editions=editions, lectio=lectio,
            others=[editions[i] for i in work["editionIds"] if i in editions and editions[i] is not lectio],
            page=load(page_file), review=review, cover=os.path.join(wd, "cover.jpg"),
            omitted=sum(1 for s in lectio["sections"] for g in s["segments"] if g.get("kind") == "omit"),
            words=sum(words(g["text"]) for s in lectio["sections"] for g in s["segments"]
                      if g.get("kind") != "omit"),
        ))
    return register, library


# ---------------------------------------------------------------- the opening passage

def cut_to(text: str, budget: int, verse: bool) -> str:
    """The longest whole-sentence (or whole-line) prefix of text within the word budget."""
    best = ""
    if verse:
        lines = text.split("\n")
        for i in range(1, len(lines)):
            cand = "\n".join(lines[:i])
            if words(cand) <= budget:
                best = cand
        return best
    for m in re.finditer(r"[.!?][\"'”’)]*(?=\s)", text):
        cand = text[:m.end()]
        if words(cand) <= budget:
            best = cand
        else:
            break
    return best


def opening(ed: dict, lo: int = 150, hi: int = 250) -> list[dict]:
    """The first 150 to 250 words of the edition, in whole paragraphs where possible.

    Each block is the exact text of a segment, or an exact prefix of one ending at a
    sentence (prose) or a line (verse). Returns blocks of {label, text, seg, whole}.
    """
    verse = ed.get("form") == "verse"
    blocks, n = [], 0
    for sec in ed["sections"]:
        label = sec["label"] + (f" · {sec['title']}" if sec.get("title") else "")
        first = True
        for seg in sec["segments"]:
            if seg.get("kind") == "omit":
                continue
            if n >= lo:
                return blocks
            text, whole = seg["text"], True
            if n + words(text) > hi:
                text, whole = cut_to(text, hi - n, verse), False
                if not text:
                    return blocks
            blocks.append(dict(label=label if first else None, text=text, seg=seg["id"], whole=whole))
            first = False
            n += words(text)
            if not whole:
                return blocks
    return blocks


def passage_html(blocks: list[dict], verse: bool) -> str:
    out = []
    for b in blocks:
        if b["label"]:
            out.append(f'<p class="lx-sec">{esc(b["label"])}</p>')
        if verse:
            out.append('<p class="lx-verse">' + "<br>".join(esc(l) for l in b["text"].split("\n")) + "</p>")
        else:
            out.append("<p>" + "<br>".join(esc(l) for l in b["text"].split("\n")) + "</p>")
    return "\n            ".join(out)


