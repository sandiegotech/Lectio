#!/usr/bin/env python3
"""The release desk: where every book stands, and when it comes out.

    python3 tools/release.py                 # status table + rewrite catalog/RELEASES.md
    python3 tools/release.py schedule DATE   # give weekly dates, from DATE, to the queue
    python3 tools/release.py approve SLUG    # the editor has read it
    python3 tools/release.py hold SLUG       # take a book off the schedule

`catalog/books.json` is the register: one entry per book, in release order. It holds only
what a person decides (order, `release`, `approved`, `print`). Everything else is read from
the repo: whether the work is ingested and drafted (content/), and how its review stands
(review/). `release` is "launch" (ships in the first release), a date "YYYY-MM-DD", or null.

The pipeline reads the same register when it builds the bundle: a launch book has no
release date, a dated book carries its date and appears in the app on that day, and a book
with no release is held back.
"""
import datetime, importlib.util, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REGISTER = os.path.join(ROOT, "catalog", "books.json")
OUT = os.path.join(ROOT, "catalog", "RELEASES.md")

def _queue():
    spec = importlib.util.spec_from_file_location("queue_", os.path.join(ROOT, "tools/review/queue.py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m

def load():
    return json.load(open(REGISTER))

def save(books):
    with open(REGISTER, "w") as f:
        json.dump(books, f, ensure_ascii=False, indent=1); f.write("\n")

def stage(book, q, drafted):
    """ingest → draft → review → fix → read → ready, the first one not yet done."""
    if not book.get("workId"):
        return "ingest", ""
    d = drafted.get(book["slug"])
    if not d:
        return "draft", ""
    rep, pat = q.reports(book["slug"]), q.patched(book["slug"])
    unrev = [o for o in d["orders"] if o not in rep]
    opened = [o for o in d["orders"] if o in rep and rep[o][1] != "A" and o not in pat]
    if d.get("partial"):
        return "draft", "%d of %d sections" % (len(d["orders"]), d["partial"])
    if unrev:
        return "review", "%d unread" % len(unrev)
    if opened:
        return "fix", "%d sections need a patch" % len(opened)
    if not book.get("approved"):
        return "read", "patch ready for the editor" if pat else "all sections clear"
    return "ready", ""

def drafted_works(q):
    out = q.works()
    for slug, w in out.items():                      # a draft shorter than its base is partial
        base = [f for f in os.listdir(os.path.join(ROOT, "content/works", w["work_id"], "editions"))
                if not f.startswith("lectio-")]
        if base:
            n = max(len(json.load(open(os.path.join(ROOT, "content/works", w["work_id"], "editions", f)))["sections"])
                    for f in base)
            if n > len(w["orders"]):
                w["partial"] = n
    return out

def report(books):
    q = _queue(); drafted = drafted_works(q); today = datetime.date.today().isoformat()
    rows = [(b, *stage(b, q, drafted)) for b in books]
    launch = [r for r in rows if r[0].get("release") == "launch"]
    dated = sorted((r for r in rows if r[0].get("release") not in (None, "launch")), key=lambda r: r[0]["release"])
    held = [r for r in rows if r[0].get("release") is None and r[0].get("workId")]
    planned = [r for r in rows if r[0].get("release") is None and not r[0].get("workId")]
    L = ["# Lectio — releases", "",
         "_Generated by `python3 tools/release.py` from `catalog/books.json`, `content/` and `review/`. Do not edit._", "",
         "%d books in the register · %d at launch · %d dated · %d waiting" % (len(books), len(launch), len(dated), len(held) + len(planned)), "",
         "Stages: ingest → draft → review → fix → read → ready. A book ships when it is **ready**.", "",
         "## At launch", "", "| Book | Author | Stage | Note |", "|---|---|---|---|"]
    L += ["| %s | %s | %s | %s |" % (b["title"], b["author"], s, n) for b, s, n in launch]
    L += ["", "## Weekly", "", "| Date | Book | Author | Stage | Note |", "|---|---|---|---|---|"]
    L += ["| %s%s | %s | %s | %s | %s |" % (b["release"], " ✓" if b["release"] <= today else "", b["title"], b["author"], s, n)
          for b, s, n in dated]
    if held:
        L += ["", "## In the bundle, not scheduled", "", "| Book | Stage | Note |", "|---|---|---|"]
        L += ["| %s | %s | %s |" % (b["title"], s, n) for b, s, n in held]
    L += ["", "## The rest of the register, in order", ""]
    L += ["%d. %s — %s%s" % (i + 1, b["title"], b["author"] or "anonymous",
                              " _(in copyright until %s)_" % b["opens"] if b.get("rights") else "")
          for i, (b, s, n) in enumerate(planned)]
    open(OUT, "w").write("\n".join(L) + "\n")
    print("%-34s %-8s %-10s %s" % ("book", "stage", "release", "note"))
    for b, s, n in launch + dated + held:
        print("%-34s %-8s %-10s %s" % (b["title"][:34], s, b.get("release") or "—", n))
    print("… and %d planned. Wrote %s" % (len(planned), os.path.relpath(OUT, ROOT)))

def main():
    books, a = load(), sys.argv[1:]
    by = {b["slug"]: b for b in books}
    if a[:1] == ["schedule"]:
        day = datetime.date.fromisoformat(a[1])
        for b in books:                                # register order is release order
            if b.get("release") == "launch" or b.get("rights"):
                continue
            b["release"] = day.isoformat(); day += datetime.timedelta(days=7)
            if len(a) > 2 and day > datetime.date.fromisoformat(a[2]):
                break
        save(books)
    elif a[:1] == ["approve"]:
        by[a[1]]["approved"] = True; save(books)
    elif a[:1] == ["hold"]:
        by[a[1]]["release"] = None; save(books)
    report(books)

if __name__ == "__main__":
    main()
